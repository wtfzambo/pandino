"""Capture a change for review-lens: the patch, one diff per file, and a manifest of facts git provides.

Usage: prepare.py --repo PATH --base REF --head REF --out DIR [--title TEXT]
"""

import argparse
from itertools import islice
import json
import os
import re
import subprocess
import sys
from pathlib import Path

# Markers tools put at the top of files they write. A hint for the agent, never a verdict.
GENERATED_HEADER = re.compile(r"<auto-generated|@generated|do not edit|code generated .* do not edit", re.IGNORECASE)
HEADER_LINES = 15
GLOSSARY_HOME = Path(os.environ.get("REVIEW_LENS_HOME", Path.home() / ".review-lens")) / "glossaries"
PREVIEW_LINES = 12
PREVIEW_WIDTH = 160


class PrepareError(RuntimeError):
    pass


def git(repo: Path, *args: str) -> str:
    result = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, errors="replace")
    if result.returncode != 0:
        raise PrepareError(f"git {' '.join(args)}: {result.stderr.strip()}")
    return result.stdout


def resolve(repo: Path, ref: str) -> str:
    return git(repo, "rev-parse", "--verify", "--end-of-options", f"{ref}^{{commit}}").strip()


def capture(repo: Path, base: str, head: str) -> tuple[str, str, str]:
    base_sha, head_sha = resolve(repo, base), resolve(repo, head)
    merge_base = git(repo, "merge-base", base_sha, head_sha).strip()
    patch = git(repo, "diff", "--no-ext-diff", "--no-textconv", "--no-color", "--find-renames",
                "--src-prefix=a/", "--dst-prefix=b/", merge_base, head_sha, "--")
    if not patch.strip():
        raise PrepareError("The change is empty: nothing between the merge base and head")
    return merge_base, head_sha, patch


# Git paints an added line that was deleted elsewhere in the change in the "newMoved" colour. Forcing both colours
# makes the two kinds of added line recognisable without depending on the user's colour settings.
NEW_COLOUR, MOVED_COLOUR = "\x1b[32m", "\x1b[34m"
ANSI = re.compile(r"\x1b\[[0-9;]*m")


def moved_lines(repo: Path, merge_base: str, head: str) -> dict[str, set[int]]:
    """For each file, the new-side line numbers of added lines that Git recognises as moved from elsewhere in the change."""
    coloured = git(repo, "-c", "color.diff.new=green", "-c", "color.diff.newMoved=blue", "-c", "color.diff.oldMoved=blue",
                   "diff", "--no-ext-diff", "--no-textconv", "--find-renames", "--color=always", "--color-moved=zebra",
                   "--color-moved-ws=allow-indentation-change", merge_base, head, "--")
    moved: dict[str, set[int]] = {}
    path, new = None, 0
    for raw in coloured.splitlines():
        line = ANSI.sub("", raw)
        paths = header_paths(line) if line.startswith("diff --git ") else None
        if paths:
            path = paths[1]
            continue
        hunk = re.match(r"@@ -\d+(?:,\d+)? \+(\d+)", line)
        if hunk:
            new = int(hunk.group(1))
            continue
        if line.startswith(("+++", "---", "\\")):
            continue
        if line.startswith("+"):
            if MOVED_COLOUR in raw or "\x1b[1;34m" in raw:
                moved.setdefault(path, set()).add(new)
            new += 1
        elif not line.startswith("-"):
            new += 1
    return moved


# Git writes a path in C-style quotes when it holds a quote, a backslash, a control or non-ASCII byte, or (in a diff
# header) when quoting is needed to tell the two paths apart; see core.quotePath in git-config(1).
QUOTED = r'"(?:[^"\\]|\\.)*"'
HEADER = re.compile(rf'diff --git (?P<old>{QUOTED}|a/.*?) (?P<new>{QUOTED}|b/.*)$')


def unquote(path: str) -> str:
    if not path.startswith('"'):
        return path
    raw = path[1:-1].encode("latin-1", "backslashreplace").decode("unicode_escape")
    return raw.encode("latin-1").decode("utf-8", "replace")


def header_paths(line: str) -> tuple[str, str] | None:
    """The old and new path of a "diff --git" line, without their a/ and b/ prefixes."""
    header = HEADER.match(line)
    if header is None:
        return None
    old, new = unquote(header.group("old")), unquote(header.group("new"))
    return old[2:], new[2:]


def split_patch(patch: str) -> dict[str, str]:
    blocks = re.split(r"(?=^diff --git )", patch, flags=re.MULTILINE)[1:]
    by_path = {}
    for block in blocks:
        paths = header_paths(block.split("\n", 1)[0])
        if paths is None:
            raise PrepareError(f"Unreadable diff header: {block[:120]!r}")
        by_path[paths[1]] = block
    return by_path


def status_of(block: str) -> str:
    if re.search(r"^new file mode", block, re.MULTILINE):
        return "added"
    if re.search(r"^deleted file mode", block, re.MULTILINE):
        return "deleted"
    if re.search(r"^rename from", block, re.MULTILINE):
        return "renamed"
    if re.search(r"^Binary files", block, re.MULTILINE):
        return "binary"
    return "modified"


def changed_lines(block: str, skip_new: set[int] = frozenset()):
    """Changed lines in order; added lines whose new-side number is in skip_new are left out."""
    new, in_hunk = 0, False
    for line in block.splitlines():
        hunk = re.match(r"@@ -\d+(?:,\d+)? \+(\d+)", line)
        if hunk:
            new, in_hunk = int(hunk.group(1)), True
        elif not in_hunk or line.startswith("\\"):
            continue
        elif line.startswith("+"):
            if new not in skip_new:
                yield line
            new += 1
        elif line.startswith("-"):
            yield line
        else:
            new += 1


def count_changes(block: str) -> tuple[int, int]:
    added = deleted = 0
    for line in changed_lines(block):
        if line.startswith("+"):
            added += 1
        else:
            deleted += 1
    return added, deleted


def generated_hints(repo: Path, head: str, path: str, status: str) -> list[str]:
    hints = []
    attrs = git(repo, "check-attr", f"--source={head}", "linguist-generated", "--", path)
    if attrs.strip().endswith(": set") or attrs.strip().endswith(": true"):
        hints.append(".gitattributes marks it linguist-generated")
    if status != "deleted":
        try:
            top = git(repo, "show", f"{head}:{path}").splitlines()[:HEADER_LINES]
        except PrepareError:
            top = []
        marker = next((line.strip() for line in top if GENERATED_HEADER.search(line)), None)
        if marker:
            hints.append(f"header says: {marker[:100]}")
    return hints


def touching_commits(repo: Path, merge_base: str, head: str) -> dict[str, list[str]]:
    log = git(repo, "log", "--format=@@%h %s", "--name-only", f"{merge_base}..{head}")
    by_file: dict[str, list[str]] = {}
    commit = None
    for line in log.splitlines():
        if line.startswith("@@"):
            commit = line[2:]
        elif line.strip() and commit:
            by_file.setdefault(unquote(line.strip()), []).append(commit)
    return by_file


def glossary_file(repo: Path) -> Path:
    """One glossary per repository, named after its origin remote, or its folder when it has none."""
    try:
        identity = git(repo, "remote", "get-url", "origin").strip()
    except PrepareError:
        identity = git(repo, "rev-parse", "--show-toplevel").strip()
    slug = re.sub(r"[^A-Za-z0-9]+", "-", re.sub(r"^\w+://|\.git$", "", identity)).strip("-").lower()
    return GLOSSARY_HOME / f"{slug[-100:]}.json"


def file_text(repo: Path, commit: str, path: str) -> str | None:
    try:
        return git(repo, "show", f"{commit}:{path}")
    except PrepareError:
        return None


def contents(repo: Path, merge_base: str, head: str, block: str, path: str, status: str) -> dict[str, str | None]:
    """The file before and after the change, so the page can show context the diff leaves out."""
    if status == "binary":
        return {"old": None, "new": None}
    old_path = header_paths(block.split("\n", 1)[0])[0]
    return {
        "old": None if status == "added" else file_text(repo, merge_base, old_path),
        "new": None if status == "deleted" else file_text(repo, head, path),
    }


def safe_name(index: int, path: str) -> str:
    return f"{index:04d}-" + re.sub(r"[^A-Za-z0-9._-]+", "_", path)[-120:] + ".diff"


def prepare(repo: Path, base: str, head: str, out: Path, title: str | None) -> dict:
    merge_base, head_sha, patch = capture(repo, base, head)
    blocks = split_patch(patch)
    commits = touching_commits(repo, merge_base, head_sha)
    moved = moved_lines(repo, merge_base, head_sha)
    out.mkdir(parents=True, exist_ok=True)
    (out / "diffs").mkdir(exist_ok=True)
    (out / "patch.diff").write_text(patch)
    files = []
    texts = {}
    for index, (path, block) in enumerate(blocks.items()):
        status = status_of(block)
        texts[path] = contents(repo, merge_base, head_sha, block, path, status)
        added, deleted = count_changes(block)
        diff_file = f"diffs/{safe_name(index, path)}"
        (out / diff_file).write_text(block)
        files.append({
            "path": path, "status": status, "added": added, "deleted": deleted, "diff": diff_file,
            "commits": commits.get(path, []), "generated_hints": generated_hints(repo, head_sha, path, status),
            "moved_in": len(moved.get(path, ())),
            "preview": [line[:PREVIEW_WIDTH] for line in islice(changed_lines(block, moved.get(path, set())), PREVIEW_LINES)],
        })
    manifest = {
        "title": title or git(repo, "log", "-1", "--format=%s", head_sha).strip(),
        "repo": str(repo.resolve()), "base": base, "head": head_sha, "merge_base": merge_base,
        "commits": git(repo, "log", "--format=%h %s", f"{merge_base}..{head_sha}").splitlines(),
        "total_added": sum(f["added"] for f in files), "total_deleted": sum(f["deleted"] for f in files),
        "files": files,
        "glossary_file": str(glossary_file(repo)),
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1))
    (out / "contents.json").write_text(json.dumps(texts, ensure_ascii=False))
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--repo", type=Path, default=Path("."))
    parser.add_argument("--base", required=True, help="The branch or commit the change goes into")
    parser.add_argument("--head", required=True, help="The branch or commit of the change")
    parser.add_argument("--out", required=True, type=Path, help="Work directory, outside the repository")
    parser.add_argument("--title")
    args = parser.parse_args()
    try:
        manifest = prepare(args.repo, args.base, args.head, args.out, args.title)
    except PrepareError as error:
        sys.exit(f"prepare: {error}")
    known = Path(manifest["glossary_file"])
    terms = len(json.loads(known.read_text())) if known.exists() else 0
    print(f"glossary: {terms} known terms in {known}")
    hinted = sum(1 for f in manifest["files"] if f["generated_hints"])
    print(f"{len(manifest['files'])} files, +{manifest['total_added']} -{manifest['total_deleted']}, "
          f"{len(manifest['commits'])} commits, {hinted} with generated hints -> {args.out / 'manifest.json'}")


if __name__ == "__main__":
    main()
