def puppeteer_dir():
    """A directory whose node_modules holds puppeteer-core, found through `npm root -g` or the current folder."""
    for root in [Path.cwd()] + [Path(r.strip()).parent for r in [subprocess.run(['npm', 'root', '-g'], capture_output=True, text=True).stdout] if r.strip()]:
        if (root / 'node_modules' / 'puppeteer-core').exists():
            return root
    return None


class ViewerTest(unittest.TestCase):
    def test_filter_and_a_saved_comment_survive_reopening(self):
        modules = puppeteer_dir() if CHROME.exists() else None
        if modules is None:
            self.skipTest('needs Google Chrome and puppeteer-core')
        with tempfile.TemporaryDirectory() as tmp:
            repo, work = Path(tmp) / 'repo', Path(tmp) / 'work'
            repo.mkdir()
            git(repo, 'init', '-q')
            git(repo, 'config', 'user.name', 'Test')
            git(repo, 'config', 'user.email', 'test@example.org')
            git(repo, 'commit', '--allow-empty', '-qm', 'base')
            for name in ['schema.sql', 'logic.py', 'notes.md']:
                (repo / name).write_text('x\n')
            git(repo, 'add', '.')
            git(repo, 'commit', '-qm', 'add')
            env = dict(os.environ, REVIEW_LENS_HOME=str(Path(tmp) / 'home'))
            subprocess.run([sys.executable, '-B', SKILL / 'prepare.py', '--repo', repo, '--base', 'HEAD~', '--head', 'HEAD', '--out', work], check=True, capture_output=True, env=env)
            files = [{'path': 'schema.sql', 'category': 'contract', 'note': 'Schema.'}, {'path': 'logic.py', 'category': 'behavior', 'note': 'Logic.'}, {'path': 'notes.md', 'category': 'support', 'note': 'Notes.'}]
            (work / 'review.json').write_text(json.dumps({'title': 'T', 'overview': 'O.', 'glossary': {}, 'steps': [{'title': 'All', 'level': 'L1', 'explanation': '<p>a</p>' * 4, 'files': files}]}))
            subprocess.run([sys.executable, '-B', SKILL / 'render.py', '--work', work], check=True, capture_output=True, env=env)
            probe = modules / 'review-lens-filter-probe.mjs'
            probe.write_text(FILTER_PROBE)
            try:
                result = subprocess.run(['node', probe, CHROME, (work / 'review.html').as_uri()], capture_output=True, text=True, timeout=60)
            finally:
                probe.unlink()
            self.assertEqual(result.returncode, 0, result.stderr)
            seen = json.loads(result.stdout.strip().splitlines()[-1])
            everything = ['logic.py', 'notes.md', 'schema.sql']
            self.assertEqual(seen, {'all': everything, 'high': ['schema.sql'], 'cleared': everything, 'reopened': everything, 'errors': []})


class OutlineTest(unittest.TestCase):
    def test_csharp_property_names_file_scoped_namespace_and_class(self):
        source = ['namespace LumaEHR.Domain.Entities;', '', '[Table("versions")]', 'public class LumaNoteVersion', '{',
                  '    /// <summary>', '    ///     What changed.', '    /// </summary>', '    public string? ChangeSummary { get; set; }', '}']
        self.assertEqual(enclosing(source, 8), ['namespace LumaEHR.Domain.Entities;', 'public class LumaNoteVersion'])

    def test_python_method_names_class_and_def(self):
        source = ['class Order:', '    def cancel(self):', '        # mark it', '        self.status = "cancelled"']
        self.assertEqual(enclosing(source, 3), ['class Order', 'def cancel(self)'])

    def test_text_without_declarations_has_no_crumbs(self):
        self.assertEqual(enclosing(['SELECT *', '  FROM orders', '  WHERE id = 1'], 2), [])

    def test_hunk_crumbs_key_each_hunk_by_its_first_changed_line(self):
        old = 'class A:\n    def f(self):\n        return 1\n'
        new = 'class A:\n    def f(self):\n        return 2\n'
        block = 'diff --git a/a.py b/a.py\n--- a/a.py\n+++ b/a.py\n@@ -2,2 +2,2 @@ class A:\n     def f(self):\n-        return 1\n+        return 2\n'
        self.assertEqual(hunk_crumbs(block, old, new), {'old:3': ['class A', 'def f(self)']})


