    def check_quoted_paths(self, quote_path):
        with tempfile.TemporaryDirectory() as tmp:
            repo, work = Path(tmp) / 'repo', Path(tmp) / 'work'
            repo.mkdir()
            git(repo, 'init', '-q')
            git(repo, 'config', 'user.name', 'Test')
