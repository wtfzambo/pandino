def git(repo, *args):
    subprocess.run(['git', '-C', repo, *args], check=True, capture_output=True)


class ReviewLensTest(unittest.TestCase):
    def test_prepare_and_render_directly(self):
        with tempfile.TemporaryDirectory() as tmp:
            repo = Path(tmp) / 'repo'
            work = Path(tmp) / 'work'
            repo.mkdir()
            git(repo, 'init', '-q')
            git(repo, 'config', 'user.name', 'Test')
            git(repo, 'config', 'user.email', 'test@example.org')
            git(repo, 'commit', '--allow-empty', '-qm', 'base')
            (repo / 'status.txt').write_text('cancelled\n')
            (repo / 'client.cs').write_text('// <auto-generated />\n')
            git(repo, 'add', '.')
            git(repo, 'commit', '-qm', 'add status')
            env = dict(os.environ, REVIEW_LENS_HOME=str(Path(tmp) / 'home'))
            subprocess.run([sys.executable, '-B', SKILL / 'prepare.py', '--repo', repo, '--base', 'HEAD~', '--head', 'HEAD', '--out', work], check=True, capture_output=True, env=env)
            files = {f['path']: f for f in json.loads((work / 'manifest.json').read_text())['files']}
            self.assertEqual(files['status.txt']['preview'], ['+cancelled'])
            self.assertTrue(files['client.cs']['generated_hints'])
            status = {'path': 'status.txt', 'category': 'contract', 'note': 'Adds cancelled.'}
            client = {'path': 'client.cs', 'category': 'mechanical', 'note': 'Generated client.'}
            review = {'title': 'Cancellation', 'overview': 'Adds a cancelled status.', 'glossary': {'Scribe': 'Writes notes for a provider.'}, 'steps': [{'title': 'Status', 'level': 'L1', 'explanation': ''.join('<p>' + 'word ' * 30 + '</p>' for _ in range(4)), 'files': [client, status]}]}

            def render():
                (work / 'review.json').write_text(json.dumps(review))
                return subprocess.run([sys.executable, '-B', SKILL / 'render.py', '--work', work], capture_output=True, text=True, env=env)

            result = render()
            self.assertEqual(result.returncode, 0, result.stderr)
            page = (work / 'review.html').read_text()
            data = json.loads(page.split('<script id="review-data" type="application/json">')[1].split('</script>')[0])
            self.assertIn('+cancelled', data['steps'][0]['files'][0]['diff'])
            self.assertEqual([f['priority'] for f in data['steps'][0]['files']], ['high', 'skip'])
            self.assertEqual(data['new_terms'], ['Scribe'])
            stored = Path(json.loads((work / 'manifest.json').read_text())['glossary_file'])
            self.assertEqual(json.loads(stored.read_text()), {'Scribe': 'Writes notes for a provider.'})
            review['glossary'] = {'Resident': 'A doctor in training.'}
            self.assertEqual(render().returncode, 0)
            data = json.loads((work / 'review.html').read_text().split('<script id="review-data" type="application/json">')[1].split('</script>')[0])
            self.assertEqual((sorted(data['glossary']), data['new_terms']), (['Resident', 'Scribe'], ['Resident']))
            self.assertEqual(sorted(json.loads(stored.read_text())), ['Resident', 'Scribe'])
            step = review['steps'][0]
            for invalid_files, error in [([status], 'missing'), ([status, client, client], 'both'), ([status, dict(client, path='invented')], 'not in the patch'), ([status, dict(client, note=' ')], 'context note')]:
                with self.subTest(error=error):
                    step['files'] = invalid_files
                    result = render()
                    self.assertNotEqual(result.returncode, 0)
                    self.assertIn(error, result.stderr)
            step['files'] = [status, client]
            review['overview'] = 'word ' * 221
            self.assertIn('over the overview limit', render().stderr)
            review['overview'] = ''
            self.assertIn('needs an overview', render().stderr)
            review['overview'] = 'Adds a cancelled status.'
            review['steps'] = [step, dict(step, files=[])]
            self.assertIn('Step titles must differ', render().stderr)
            review['steps'] = [step]
            step['findings'] = [{'title': 'Question', 'file': 'elsewhere', 'severity': 'low'}]
            self.assertIn('not a file of step', render().stderr)


    def test_lines_moved_from_another_file_are_counted_and_left_out_of_the_preview(self):
        with tempfile.TemporaryDirectory() as tmp:
            repo, work = Path(tmp) / 'repo', Path(tmp) / 'work'
            repo.mkdir()
            git(repo, 'init', '-q')
            git(repo, 'config', 'user.name', 'Test')
            git(repo, 'config', 'user.email', 'test@example.org')
            moved = [f'    value_{i} = compute_{i}(input)' for i in range(12)]
            (repo / 'page.py').write_text('def render():\n' + '\n'.join(moved) + '\n')
            git(repo, 'add', '.')
            git(repo, 'commit', '-qm', 'base')
            (repo / 'page.py').write_text('def render():\n    return helper()\n')
            (repo / 'helper.py').write_text('def helper():\n' + '\n'.join(moved) + '\n    return value_0\n')
            git(repo, 'add', '.')
            git(repo, 'commit', '-qm', 'extract helper')
            env = dict(os.environ, REVIEW_LENS_HOME=str(Path(tmp) / 'home'))
            subprocess.run([sys.executable, '-B', SKILL / 'prepare.py', '--repo', repo, '--base', 'HEAD~', '--head', 'HEAD', '--out', work], check=True, capture_output=True, env=env)
            helper = {f['path']: f for f in json.loads((work / 'manifest.json').read_text())['files']}['helper.py']
            self.assertEqual((helper['added'], helper['moved_in']), (14, 12))
            self.assertEqual(helper['preview'], ['+def helper():', '+    return value_0'])


class OutlineTest(unittest.TestCase):
    def test_csharp_property_names_file_scoped_namespace_and_class(self):
        source = ['namespace LumaEHR.Domain.Entities;', '', '[Table("versions")]', 'public class LumaNoteVersion', '{',
                  '    /// <summary>', '    ///     What changed.', '    /// </summary>', '    public string? ChangeSummary { get; set; }', '}']
        self.assertEqual(enclosing(source, 8), ['namespace LumaEHR.Domain.Entities;', 'public class LumaNoteVersion'])

    def test_python_method_names_class_and_def(self):
        source = ['class Order:', '    def cancel(self):', '        # mark it', '        self.status = "cancelled"']
        self.assertEqual(enclosing(source, 3), ['class Order', 'def cancel(self)'])

    def test_text_without_declarations_has_no_crumbs(self):
        self.assertEqual(enclosing(['SELECT *', '  FROM orders', '  WHERE id = 1'], 2), [])

    def test_hunk_crumbs_key_each_hunk_by_its_first_changed_line(self):
        old = 'class A:\n    def f(self):\n        return 1\n'
        new = 'class A:\n    def f(self):\n        return 2\n'
        block = 'diff --git a/a.py b/a.py\n--- a/a.py\n+++ b/a.py\n@@ -2,2 +2,2 @@ class A:\n     def f(self):\n-        return 1\n+        return 2\n'
        self.assertEqual(hunk_crumbs(block, old, new), {'old:3': ['class A', 'def f(self)']})


